"use strict";

const fs = require("fs");
const path = require("path");

const distDirectory = path.join(process.cwd(), "dist");

const cssTag =
  '<link id="cai-mobile-fix-css" rel="stylesheet" href="/colleagueai-mobile-fix.css?v=20260713">';

const jsTag =
  '<script id="cai-mobile-fix-js" src="/colleagueai-mobile-fix.js?v=20260713" defer></script>';

const textRepairs = [
  ["â„¢", "™"],
  ["â€™", "’"],
  ["â€œ", "“"],
  ["â€", "”"],
  ["â€“", "–"],
  ["â€”", "—"],
  ["Â©", "©"],
  ["Â®", "®"],
  ["Â·", "·"],
  ["Ã—", "×"],
  ["Â ", " "]
];

function findFiles(directory) {
  const files = [];

  for (const entry of fs.readdirSync(directory, {
    withFileTypes: true
  })) {
    const completePath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...findFiles(completePath));
    } else {
      files.push(completePath);
    }
  }

  return files;
}

function repairText(html) {
  let repaired = html;

  for (const replacement of textRepairs) {
    repaired = repaired
      .split(replacement[0])
      .join(replacement[1]);
  }

  return repaired;
}

function injectCss(html) {
  if (html.includes('id="cai-mobile-fix-css"')) {
    return html;
  }

  /*
    Standard complete HTML document.
  */
  if (/<\/head>/i.test(html)) {
    return html.replace(
      /<\/head>/i,
      `  ${cssTag}\n</head>`
    );
  }

  /*
    Document with a body but no explicit closing head.
  */
  if (/<body\b[^>]*>/i.test(html)) {
    return html.replace(
      /<body\b[^>]*>/i,
      function (bodyTag) {
        return `${cssTag}\n${bodyTag}`;
      }
    );
  }

  /*
    HTML fragments generated by localization scripts.
  */
  return `${cssTag}\n${html}`;
}

function injectJavaScript(html) {
  if (html.includes('id="cai-mobile-fix-js"')) {
    return html;
  }

  /*
    Standard complete HTML document.
  */
  if (/<\/body>/i.test(html)) {
    return html.replace(
      /<\/body>/i,
      `  ${jsTag}\n</body>`
    );
  }

  /*
    A document may have </html> but no explicit </body>.
  */
  if (/<\/html>/i.test(html)) {
    return html.replace(
      /<\/html>/i,
      `  ${jsTag}\n</html>`
    );
  }

  /*
    Generated HTML fragment: append the deferred script safely.
  */
  return `${html.trimEnd()}\n${jsTag}\n`;
}

if (!fs.existsSync(distDirectory)) {
  throw new Error(
    "The dist folder does not exist. The production build did not complete."
  );
}

const htmlFiles = findFiles(distDirectory).filter(function (file) {
  return file.toLowerCase().endsWith(".html");
});

if (htmlFiles.length === 0) {
  throw new Error("No HTML files were found in dist.");
}

let changedFiles = 0;

for (const file of htmlFiles) {
  const original = fs.readFileSync(file, "utf8");

  let html = repairText(original);
  html = injectCss(html);
  html = injectJavaScript(html);

  if (html !== original) {
    fs.writeFileSync(file, html, "utf8");
    changedFiles += 1;
  }
}

console.log(
  "Responsive patch checked " +
  htmlFiles.length +
  " HTML files and updated " +
  changedFiles +
  "."
);